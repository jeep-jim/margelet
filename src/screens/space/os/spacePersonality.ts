import type { SpaceOSDecision, SpaceOSMemory } from './types';

function userName(memory: SpaceOSMemory) {
  return memory.userName ? `${memory.userName}, ` : '';
}

function qnorm(query: string) {
  return query.toLowerCase().replace(/ё/g, 'е').trim();
}

function has(q: string, re: RegExp) {
  return re.test(q);
}

function pick(seed: string, items: string[]) {
  const n = seed.split('').reduce((sum, ch) => sum + ch.charCodeAt(0), 0);
  return items[Math.abs(n) % items.length];
}

export function humanChat(query: string, decision: SpaceOSDecision, memory: SpaceOSMemory) {
  const q = qnorm(query);
  const prefix = userName(memory);

  if (has(q, /привет|здравств|салам|hello|hi\b|hey\b/)) {
    return pick(q, [
      `${prefix}привет 😄 Я Space. Можем просто поболтать, что-нибудь найти или собрать красивый ответ из интернета.`,
      `${prefix}я здесь 🙂 Хочешь поговорим по-человечески или сразу полезем искать что-то в сети?`,
      `${prefix}привет. Сегодня могу быть собеседником, поиском, погодой, музыкой, графиком или маленьким браузером внутри margeleT.`,
    ]);
  }

  if (has(q, /ты\s+тут|ты\s+здесь|слышишь|слушаешь|живой|на месте/)) {
    return `${prefix}тут 🙂 Я не человек, но стараюсь быть нормальным собеседником: сначала думаю, потом ищу, потом показываю. Не только Telegram — весь открытый веб.`;
  }

  if (has(q, /что\s+умеешь|что\s+ты\s+можешь|возможности|help|помощь/)) {
    return 'Могу поговорить, объяснить тему, найти информацию в интернете, показать погоду, картинки, видео, музыку, графики, товары, биографии и свежие сигналы из Telegram как дополнение. Напиши просто человечески: “погода Берлин”, “кто такой Моцарт”, “включи Billie Jean”, “купить сахар”, “покажи график биткоина”.';
  }

  if (has(q, /просто\s+общаемся|поговорим|поболтаем|давай\s+поговорим|поздороваться/)) {
    return pick(q, [
      'Давай 🙂 Без карточек и без суеты. Просто говорим. Что у тебя сейчас в голове?',
      'Хорошо. Тогда я не лезу в поиск, а остаюсь рядом как собеседник. С чего начнём?',
      'Можно и просто поговорить. Не каждый запрос должен превращаться в выдачу 😄',
    ]);
  }

  if (has(q, /как\s+дела|как\s+жизнь|как\s+ты|ну\s+ты\s+как/)) {
    return 'Потихоньку оживаю 😄 Ещё не идеальный, но уже учусь отличать разговор от поиска. А у тебя как настроение?';
  }

  if (has(q, /скучно|устал|тяжело|плохо|грустно|одиноко|выгорел|заеб/)) {
    return `${prefix}понял. Тогда без умничанья. Можно сделать три вещи: выдохнуть, разобрать что именно давит, или переключиться на что-то лёгкое — музыку, картинки, кино, смешную тему.`;
  }

  if (has(q, /совет|иде[ия]|бизнес|деньг|работ|карьер|заработ|как\s+заработать/)) {
    return `${prefix}давай по-взрослому. Я не буду обещать волшебную схему. Но могу помочь собрать маршрут: что ты умеешь, где есть спрос, какие первые шаги, и где найти людей/источники по теме. Если хочешь — начнём с твоих навыков и интересов.`;
  }

  if (has(q, /кошка|кот|собак|животн/)) {
    return 'Кошки — отдельная цивилизация 😄 Если коротко: они не “равнодушные”, они просто иначе показывают привязанность. Могу поговорить про поведение, здоровье, уход или просто подобрать милые картинки.';
  }

  if (has(q, /пенси|реформ|политик|экономик|общество/)) {
    return 'Тема непростая. Я бы не сводил её к лозунгам: тут есть деньги государства, демография, доверие людей и качество управления. Могу объяснить простыми словами или найти актуальные источники.';
  }

  if (has(q, /истори|войн|импер|революц|ссср|рим|египет/)) {
    return 'Историю лучше разбирать слоями: что точно известно, кто это описывал, кому было выгодно, и какие последствия остались сейчас. Могу рассказать кратко или собрать источники.';
  }

  if (has(q, /фильм|кино|сериал|посоветуй.*вечер/)) {
    return 'Могу подобрать кино под настроение. Например: лёгкое, умное, мрачное, смешное, фантастика, триллер или “чтобы просто выключить голову”.';
  }

  if (has(q, /почему|зачем|как\s+думаешь|что\s+думаешь/)) {
    return 'Я бы разделил это на две части: факты и смысл. Факты можно проверить, а смысл — обсудить. Скажу честно: иногда хороший ответ начинается не с поиска, а с нормального вопроса к самому себе.';
  }

  if (q.length <= 3) {
    return 'Я подхватил, но фраза совсем короткая. Можно кинуть ещё пару слов — я сам выберу: поговорить, поискать или показать виджет.';
  }

  if (decision.tool === 'chat') {
    return `${prefix}${pick(q, [
      'слышу мысль. Сначала отвечу по смыслу, потом при необходимости подключу сеть и виджеты.',
      'интересная мысль. Я могу ответить своими словами, поспорить или собрать факты из сети — выбери любой режим, а я подстроюсь.',
      'окей, давай разберём. Сначала смысл: что в этом для тебя главное — понять, решить, сравнить или просто поговорить?',
    ])}`;
  }

  return `${prefix}сейчас соберу это аккуратно.`;
}

export function actionLead(decision: SpaceOSDecision) {
  const subject = decision.subject || decision.query;
  switch (decision.tool) {
    case 'weather': return `Сейчас покажу реальную погоду: ${subject} 🌤️`;
    case 'music': return `Ищу, где это можно включить: ${subject} 🎵`;
    case 'images': return `Собираю картинки из открытого веба: ${subject} 🖼️`;
    case 'video': return `Ищу видео и превью: ${subject} 🎬`;
    case 'finance': return `Собираю график: ${subject} 📈`;
    case 'shopping': return `Ищу варианты покупки: ${subject} 🛒`;
    case 'biography': return `Собираю биографию и факты: ${subject} 📚`;
    case 'profile': return `Поищу профиль или упоминания: ${subject} 👤`;
    case 'tunnel': return `Собираю туннель интереса: ${subject} 🧲`;
    case 'product': return 'Покажу, что такое margeleT и зачем нужен Space.';
    default: return `Сейчас посмотрю: ${subject}`;
  }
}
