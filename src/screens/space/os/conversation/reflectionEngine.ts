import type { ConversationContext } from './types';
import { pickBySeed } from './textTools';
import { userPrefix } from './humanizer';

export function reflectionLine(ctx: ConversationContext) {
  const prefix = userPrefix(ctx);

  if (ctx.mood === 'tired') {
    return pickBySeed(ctx.query, [
      `${prefix}похоже, накопилось. Иногда усталость — это не про тело, а про то, что голова слишком долго держит всё сразу.`,
      `${prefix}понимаю. В такие моменты не всегда нужен “план на жизнь”; иногда сначала надо просто снять давление с головы.`,
      `${prefix}давай без геройства. Если батарейка села, сначала надо понять: ты физически устал или больше перегружен мыслями?`,
    ]);
  }

  if (ctx.mood === 'sad') {
    return pickBySeed(ctx.query, [
      `${prefix}сочувствую. Не буду сразу закидывать советами — иногда человеку важнее, чтобы его нормально услышали.`,
      `${prefix}бывает. Давай аккуратно: что сейчас тяжелее всего — одиночество, неопределённость или ощущение, что всё застыло?`,
      `${prefix}я рядом в рамках чата 🙂 Не волшебник, но могу помочь разложить мысли без давления.`,
    ]);
  }

  if (ctx.need === 'explain') {
    return pickBySeed(ctx.query, [
      `${prefix}я бы объяснил это не одной фразой, а слоями: что это значит, почему так получилось и что из этого следует.`,
      `${prefix}тут важно отделить факты от мнений. Факты можно проверить, а смысл — спокойно обсудить.`,
      `${prefix}давай разберём простыми словами, без академического тумана.`,
    ]);
  }

  return pickBySeed(ctx.query, [
    `${prefix}я бы посмотрел на это с двух сторон: что видно снаружи и что на самом деле может стоять за этим.`,
    `${prefix}если коротко: тут не один ответ, а несколько возможных причин.`,
    `${prefix}мне кажется, здесь важнее не “правильный ответ”, а нормальная рамка, в которой можно думать дальше.`,
  ]);
}
