import type { ConversationContext } from './types';
import { pickBySeed } from './textTools';
import { userPrefix } from './humanizer';

export function dreamLine(ctx: ConversationContext) {
  const prefix = userPrefix(ctx);
  if (/бизнес|дело|деньг|заработ|иде/i.test(ctx.normalized)) {
    return pickBySeed(ctx.query, [
      `${prefix}если мечта — свой бизнес, я бы начал не с “какая ниша стреляет”, а с трёх вопросов: что ты умеешь, кому это больно и как проверить спрос за неделю.`,
      `${prefix}можно собрать карту идей: быстрые деньги, долгий проект, услуга руками, цифровой продукт или медиа вокруг твоего опыта.`,
      `${prefix}тут можно сделать умно: сначала найти маленькую боль людей, потом самый дешёвый способ её проверить, и только потом думать про деньги.`,
    ]);
  }

  return pickBySeed(ctx.query, [
    `${prefix}можно подойти творчески. Я бы не искал сразу идеальный ответ — лучше набросать 3-4 направления и выбрать живое.`,
    `${prefix}давай мыслить шире. Иногда лучший вариант не тот, который очевиден, а тот, который можно быстро попробовать.`,
    `${prefix}если бы мы строили это как проект, я бы сначала сделал маленький тест, а не огромный план.`,
  ]);
}
