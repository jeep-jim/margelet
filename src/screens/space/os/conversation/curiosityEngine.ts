import type { ConversationContext } from './types';
import { pickBySeed } from './textTools';
import { userPrefix } from './humanizer';

export function curiosityLine(ctx: ConversationContext) {
  const prefix = userPrefix(ctx);
  if (ctx.need === 'advice') {
    return pickBySeed(ctx.query, [
      `${prefix}давай не прыгать сразу к решению. Что здесь важнее: деньги, свобода, спокойствие или новый старт?`,
      `${prefix}интересно. Я бы сначала понял мотив: ты хочешь заработать, выбраться из рутины или проверить идею?`,
      `${prefix}тут лучше начать не с советов, а с цели. Что должно измениться, если всё получится?`,
    ]);
  }

  if (ctx.need === 'idea') {
    return pickBySeed(ctx.query, [
      `${prefix}можем пофантазировать. Иногда хорошая идея рождается не из “что сейчас модно”, а из того, что тебя реально бесит или цепляет.`,
      `${prefix}давай попробуем найти направление. Есть три дороги: быстро проверить спрос, найти боль людей или собрать идею из твоих навыков.`,
      `${prefix}я бы начал с простого: что тебе самому было бы интересно делать даже без идеального плана?`,
    ]);
  }

  return pickBySeed(ctx.query, [
    `${prefix}любопытно 👀 Тут можно пойти глубже, но сначала я попробую уловить, что именно тебя зацепило.`,
    `${prefix}хорошая тема. Давай не будем делать вид, что она простая — лучше разложим её на понятные части.`,
    `${prefix}я понял направление. Можно обсудить своими словами, а если понадобятся факты — я подключу поиск.`,
  ]);
}
